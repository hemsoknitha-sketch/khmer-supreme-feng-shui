        """Return all topics or topics filtered by category."""
        res = []
        for t in TOPICS_METADATA:
            if category_id and t["cat"] != category_id:
                continue
            res.append({
                "topic_id": t["id"],
                "category_id": t["cat"],
                "name_kh": t["name_kh"],
                "name_en": t["name_en"],
                "summary": t["essence"],
                "lesson_start": (t["id"] - 1) * 10 + 1,
                "lesson_end": t["id"] * 10
            })
        return res

